/** 곡선 하나를 공개 함수 3개로 감싼 호출 묶음. */
interface Subject {
  readonly name: string;
  readonly length: (options?: LengthOptions) => number;
  readonly lengthAtT: (t: number, options?: LengthOptions) => number;
  readonly tAtLength: (distance: number, options?: TAtLengthOptions) => number;
}

/** length·lengthAtT에 넣는 옵션 목록. */
const LENGTH_OPTIONS: ReadonlyArray<{ label: string; options: LengthOptions | undefined }> = [
  { label: '기본', options: undefined },
  { label: 'segments=0', options: { segments: 0 } },
  { label: 'segments=1', options: { segments: 1 } },
  { label: 'segments=3', options: { segments: 3 } },
  { label: 'segments=25', options: { segments: 25 } },
];

/** tAtLength에 넣는 옵션 목록. 기본 외에는 탐색 제어 옵션을 하나씩 바꾼다. */
const T_AT_LENGTH_OPTIONS: ReadonlyArray<{ label: string; options: TAtLengthOptions | undefined }> = [
  { label: '기본', options: undefined },
  { label: 'segments=0', options: { segments: 0 } },
  { label: 'segments=1', options: { segments: 1 } },
  { label: 'segments=3', options: { segments: 3 } },
  { label: 'segments=25', options: { segments: 25 } },
  { label: 'tolerance=1e-3', options: { tolerance: 1e-3 } },
  { label: 'maxIterations=5', options: { maxIterations: 5 } },
  { label: 'maxIterations=0', options: { maxIterations: 0 } },
  { label: 'tolerance=0 maxIterations=3', options: { tolerance: 0, maxIterations: 3 } },
];

/** lengthAtT에 넣는 t 목록. */
const T_VALUES: ReadonlyArray<{ label: string; t: number }> = [
  { label: 'NaN', t: Number.NaN },
  { label: '-0', t: -0 },
  { label: '-1', t: -1 },
  { label: '0', t: 0 },
  { label: '0.5', t: 0.5 },
  { label: '1', t: 1 },
  { label: '2', t: 2 },
];

/** number를 -0, NaN까지 구분되는 문자열로 바꾼다. 문자열은 round-trip이 정확해 비트 단위 비교가 된다. */
function fmt(n: number): string {
  return Object.is(n, -0) ? '-0' : String(n);
}

/**
 * 총길이에서 경계 distance 목록을 만든다.
 * 음수, 0, -0, 총길이 미만, 총길이, 초과, NaN, Infinity를 담는다.
 */
function distancesFor(total: number): Array<{ label: string; distance: number }> {
  return [
    { label: '음수', distance: -1 },
    { label: '0', distance: 0 },
    { label: '-0', distance: -0 },
    { label: '총길이의 1/4', distance: total * 0.25 },
    { label: '총길이의 1/2', distance: total * 0.5 },
    { label: '총길이 직전', distance: total * 0.999999 },
    { label: '총길이', distance: total },
    { label: '총길이의 2배', distance: total * 2 },
    { label: 'NaN', distance: Number.NaN },
    { label: 'Infinity', distance: Number.POSITIVE_INFINITY },
  ];
}

/**
 * 곡선 하나에 대해 3개 공개 함수의 출력을 모두 기록한다.
 * 키는 `함수/입력/옵션` 형태이고 값은 fmt 문자열이다.
 * tAtLength의 distance는 옵션마다 그 옵션으로 계산한 총길이에서 만든다.
 */
function record(subject: Subject): Record<string, string> {
  const out: Record<string, string> = {};

  for (const { label, options } of LENGTH_OPTIONS) {
    out[`length/${label}`] = fmt(subject.length(options));
    for (const { label: tLabel, t } of T_VALUES) {
      out[`lengthAtT/t=${tLabel}/${label}`] = fmt(subject.lengthAtT(t, options));
    }
  }

  for (const { label, options } of T_AT_LENGTH_OPTIONS) {
    const total = subject.lengthAtT(1, options);
    out[`총길이/${label}`] = fmt(total);
    const targets = label === '기본' ? distancesFor(total) : distancesFor(total).filter((d) => d.distance > 0);
    for (const { label: dLabel, distance } of targets) {
      out[`tAtLength/${dLabel}/${label}`] = fmt(subject.tAtLength(distance, options));
    }
  }

  return out;
}

/** cubic Bezier 4점을 공개 함수 3개로 감싼다. */
function cubicSubject(name: string, p0: XYInput, p1: XYInput, p2: XYInput, p3: XYInput): Subject {
  return {
    name,
    length: (o) => cubicLength(p0, p1, p2, p3, o),
    lengthAtT: (t, o) => cubicLengthAtT(p0, p1, p2, p3, t, o),
    tAtLength: (d, o) => cubicTAtLength(p0, p1, p2, p3, d, o),
  };
}

/** quadratic Bezier 3점을 공개 함수 3개로 감싼다. */
function quadraticSubject(name: string, p0: XYInput, p1: XYInput, p2: XYInput): Subject {
  return {
    name,
    length: (o) => quadraticLength(p0, p1, p2, o),
    lengthAtT: (t, o) => quadraticLengthAtT(p0, p1, p2, t, o),
    tAtLength: (d, o) => quadraticTAtLength(p0, p1, p2, d, o),
  };
}

/** center arc를 공개 함수 3개로 감싼다. */
function arcSubject(
  name: string,
  rx: number,
  ry: number,
  startAngle: number,
  endAngle: number,
  xRotation = 0
): Subject {
  const centerArc: CenterArcLike = {
    cx: 1,
    cy: 2,
    rx,
    ry,
    xRotation,
    startAngle,
    endAngle,
    sweep: endAngle >= startAngle,
  };
  return {
    name,
    length: (o) => arcLength(centerArc, o),
    lengthAtT: (t, o) => arcLengthAtT(centerArc, t, o),
    tAtLength: (d, o) => arcTAtLength(centerArc, d, o),
  };
}

/** 곡선 목록을 이름 → 기록 map으로 바꾼다. */
function recordAll(subjects: readonly Subject[]): Record<string, Record<string, string>> {
  return Object.fromEntries(subjects.map((s) => [s.name, record(s)]));
}

